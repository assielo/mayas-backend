DELIMITER $$
CREATE TRIGGER `before_insert_agent` BEFORE INSERT ON `agents` FOR EACH ROW BEGIN
    DECLARE max_id INT DEFAULT 0;
    DECLARE prefixe VARCHAR(10);
    DECLARE nom_du_poste VARCHAR(100);

    -- 1. Récupération de l'intitulé du poste
    IF NEW.poste_id IS NOT NULL THEN
        SELECT intitule INTO nom_du_poste 
        FROM postes 
        WHERE id = NEW.poste_id;
    END IF;

    -- 2. Sélection du préfixe selon le poste
    IF nom_du_poste LIKE '%Superviseur%' THEN
        SET prefixe = 'SUP-M-';
    ELSE
        SET prefixe = 'AGT-M-';
    END IF;

    -- 3. Extraction et incrémentation du dernier numéro utilisé
    SELECT IFNULL(MAX(CAST(SUBSTRING(matricule, CHAR_LENGTH(prefixe) + 1) AS UNSIGNED)), 0) + 1 
    INTO max_id 
    FROM agents 
    WHERE matricule LIKE CONCAT(prefixe, '%');

    -- 4. Attribution du nouveau matricule
    SET NEW.matricule = CONCAT(prefixe, LPAD(max_id, 3, '0'));
END
$$
